# ---------------------------------------------------------------- commands

def cmd_new(args):
    name = args.name
    if not NAME_RE.match(name):
        print(
            "error: invalid agent name %r: use lowercase letters, numbers, and hyphens only"
            % name,
            file=sys.stderr,
        )
        return 2
    base = os.path.abspath(args.dir)
    target = os.path.join(base, name)
    if os.path.isdir(target) and os.listdir(target) and not args.force:
        print(
            "error: directory %r is not empty; pass --force to overwrite" % target,
            file=sys.stderr,
        )
        return 2
    os.makedirs(target, exist_ok=True)
    files = {
        "manifest.json": _manifest_template(name),
        "SKILL.md": _skill_template(name),
        "agent.py": _agent_template(name),
        os.path.join("tests", "test_agent.py"): _scaffold_test_template(name),
        "README.md": _readme_template(name),
    }
    for relpath, content in files.items():
        full = os.path.join(target, relpath)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as fh:
            fh.write(content)
    print("scaffolded agent %r at %s" % (name, target))
    return 0


def cmd_validate(args):
    project = os.path.abspath(args.project_dir)
    problems = []
    if not os.path.isdir(project):
        print("error: not a directory: %s" % project, file=sys.stderr)
        return 1
    manifest_path = os.path.join(project, "manifest.json")
    if not os.path.isfile(manifest_path):
        problems.append("missing manifest.json")
        manifest = None
    else:
        try:
            with open(manifest_path, "r", encoding="utf-8") as fh:
                manifest = json.load(fh)
        except (OSError, json.JSONDecodeError) as exc:
            problems.append("manifest.json does not parse: %s" % exc)
            manifest = None
        if manifest is not None:
            if not isinstance(manifest, dict):
                problems.append("manifest.json must contain a JSON object")
                manifest = None
            else:
                for key in REQUIRED_MANIFEST_KEYS:
                    if key not in manifest:
                        problems.append("manifest.json missing required key: %s" % key)
                if "skills" in manifest and not isinstance(manifest["skills"], list):
                    problems.append("manifest.json 'skills' must be a list")
                entrypoint = manifest.get("entrypoint")
                if isinstance(entrypoint, str):
                    entry_path = os.path.join(project, entrypoint)
                    if not os.path.isfile(entry_path):
                        problems.append("entrypoint not found: %s" % entrypoint)
    skill_path = os.path.join(project, "SKILL.md")
    if not os.path.isfile(skill_path):
        problems.append("missing SKILL.md")
    if problems:
        print("invalid agent project: %s" % project)
        for p in problems:
            print("  - %s" % p)
        return 1
    print("valid agent project: %s" % project)
    return 0


def build_parser():
    parser = argparse.ArgumentParser(prog="agent-foundry", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    p_new = sub.add_parser("new", help="Scaffold a new agent project.")
    p_new.add_argument("name", help="Agent name: lowercase letters, numbers, hyphens only.")
    p_new.add_argument("--dir", default=".", help="Parent directory (default: current dir).")
    p_new.add_argument("--force", action="store_true", help="Overwrite a non-empty directory.")
    p_new.set_defaults(func=cmd_new)

    p_val = sub.add_parser("validate", help="Validate a scaffolded agent project.")
    p_val.add_argument("project_dir", help="Path to the agent project directory.")
    p_val.set_defaults(func=cmd_validate)

    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
